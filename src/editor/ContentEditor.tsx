import React, { useEffect, useRef, useState } from "react";

let instanceSequence = 0;

interface TinyEditor {
  on: (events: string, handler: () => void) => void;
  getContent: () => string;
  isHidden: () => boolean;
  setMode: (mode: string) => void;
  remove: () => void;
  getBody: () => HTMLElement;
  execCommand: (command: string) => void;
}
interface CoreEditor {
  wpActiveEditor?: string;
  tinyMCEPreInit: {
    mceInit: Record<string, Record<string, unknown>>;
    qtInit: Record<string, Record<string, unknown>>;
  };
  tinymce?: {
    init: (settings: Record<string, unknown>) => void;
    get: (id: string) => TinyEditor | undefined;
  };
  quicktags?: (settings: Record<string, unknown>) => void;
  wp: {
    editor: {
      remove: (id: string) => void;
      getContent: (id: string) => string;
    };
  };
}

/** Core owns this DOM island; React must not reconcile TinyMCE's wrappers.
 * Only user edits leave the island. Autosave responses never reset its value,
 * selection or undo stack. A new working version remounts the island. */
export function ContentEditor({
  markup,
  initialContent,
  disabled,
  label,
  errorLabel,
  onChange,
  onLeave,
}: {
  markup: string;
  initialContent: string;
  disabled: boolean;
  label: string;
  errorLabel: string;
  onChange: (content: string) => void;
  onLeave: () => void;
}) {
  const host = useRef<HTMLDivElement>(null);
  const callbacks = useRef({ onChange, onLeave, disabled });
  callbacks.current = { onChange, onLeave, disabled };
  const [failed, setFailed] = useState(false);
  const [editorId, setEditorId] = useState("");
  const liveId = useRef("");

  useEffect(() => {
    const node = host.current!;
    const core = window as unknown as CoreEditor;
    // Unique per effect lifetime, including StrictMode remounts: a delayed
    // TinyMCE init from an old instance must never attach to the new textarea.
    const id = `forma-content-${++instanceSequence}`;
    liveId.current = id;
    setEditorId(id);
    let alive = true;
    let active = false;
    let timer: ReturnType<typeof setTimeout> | undefined;
    let editor: TinyEditor | undefined;
    let lastVisual = "";
    let initialized = false;
    let sizeObserver: ResizeObserver | undefined;
    let resizeFrame = 0;
    // This markup is generated by wp_editor with an empty value. Insert the
    // user's content as a textarea value, never as executable HTML.
    node.innerHTML = markup.replaceAll("forma-content", id);
    const content = node.parentElement!;
    const labelElement = content.querySelector<HTMLElement>("label")!;
    const tools = node.querySelector<HTMLElement>(".wp-editor-tools")!;
    // Keep the stacked sticky rows aligned when labels/buttons wrap. Leave
    // WordPress's DOM intact so media, tabs and editor teardown retain ownership.
    const measureChrome = () => {
      content.style.setProperty(
        "--forma-content-label-height",
        `${labelElement.getBoundingClientRect().height}px`,
      );
      content.style.setProperty(
        "--forma-content-tools-height",
        `${tools.getBoundingClientRect().height}px`,
      );
    };
    const chromeObserver = new ResizeObserver(measureChrome);
    chromeObserver.observe(labelElement);
    chromeObserver.observe(tools);
    measureChrome();
    const textarea = node.querySelector<HTMLTextAreaElement>(`#${id}`)!;
    textarea.value = initialContent;
    const emit = () => {
      if (!alive || callbacks.current.disabled) return;
      callbacks.current.onChange(core.wp.editor.getContent(id));
    };
    const visualChange = () => {
      if (!initialized || !editor || editor.isHidden()) return;
      const html = editor.getContent();
      if (html === lastVisual) return;
      lastVisual = html;
      emit();
    };
    const owned = (element: Element | null) =>
      Boolean(
        element &&
        (node.contains(element) ||
          element.closest(
            ".mce-container, .mce-widget, .media-modal, #wp-link-wrap, #wp-link-backdrop",
          )),
      );
    const dialogOpen = () =>
      Array.from(
        document.querySelectorAll<HTMLElement>(
          ".media-modal, .mce-window, #wp-link-wrap",
        ),
      ).some((element) => element.getClientRects().length > 0);
    const checkLeave = () => {
      clearTimeout(timer);
      timer = setTimeout(() => {
        if (active && !owned(document.activeElement) && !dialogOpen()) {
          active = false;
          callbacks.current.onLeave();
        }
      }, 0);
    };
    const focus = () => {
      if (owned(document.activeElement)) active = true;
      else checkLeave();
    };
    // Quicktags and media insertion also dispatch change on the textarea.
    textarea.addEventListener("input", emit);
    textarea.addEventListener("change", emit);
    document.addEventListener("focusin", focus);
    window.addEventListener("blur", checkLeave);
    try {
      const settings = core.tinyMCEPreInit.mceInit["forma-content"];
      if (core.tinymce && settings) {
        const previousSetup = settings.setup as
          ((editor: TinyEditor) => void) | undefined;
        const config = {
          ...settings,
          id,
          wp_skip_init: false,
          selector: `#${id}`,
          setup: (instance: TinyEditor) => {
            editor = instance;
            previousSetup?.(instance);
            instance.on("init", () => {
              if (!alive) {
                instance.remove();
                return;
              }
              lastVisual = instance.getContent();
              initialized = true;
              // Core handles content sizing and fullscreen. Observe layout too:
              // images and panel resizing need not produce an editor event.
              sizeObserver = new ResizeObserver(() => {
                cancelAnimationFrame(resizeFrame);
                resizeFrame = requestAnimationFrame(() => {
                  if (alive && !instance.isHidden())
                    instance.execCommand("wpAutoResize");
                });
              });
              sizeObserver.observe(instance.getBody());
              instance.setMode(
                callbacks.current.disabled ? "readonly" : "design",
              );
            });
            instance.on("input change Undo Redo", visualChange);
            instance.on("focus", () => {
              active = true;
            });
            instance.on("blur", checkLeave);
          },
        };
        core.tinyMCEPreInit.mceInit[id] = config;
        if (node.querySelector(".tmce-active")) core.tinymce.init(config);
      }
      // Core may have created an instance while printing its footer; remove
      // via wp.editor.remove on teardown, including Quicktags registry entries.
      core.quicktags?.({ ...core.tinyMCEPreInit.qtInit["forma-content"], id });
      core.wpActiveEditor = id;
    } catch {
      setFailed(true);
    }
    return () => {
      alive = false;
      chromeObserver.disconnect();
      sizeObserver?.disconnect();
      cancelAnimationFrame(resizeFrame);
      clearTimeout(timer);
      textarea.removeEventListener("input", emit);
      textarea.removeEventListener("change", emit);
      document.removeEventListener("focusin", focus);
      window.removeEventListener("blur", checkLeave);
      core.wp.editor.remove(id);
      delete core.tinyMCEPreInit.mceInit[id];
      delete core.tinyMCEPreInit.qtInit[id];
      if (core.wpActiveEditor === id) core.wpActiveEditor = undefined;
      node.replaceChildren();
    };
  }, []);

  useEffect(() => {
    if (host.current) host.current.inert = disabled;
    (window as unknown as CoreEditor).tinymce
      ?.get(liveId.current)
      ?.setMode(disabled ? "readonly" : "design");
  }, [disabled]);

  return (
    <div className="forma-editor__content">
      <label htmlFor={editorId}>{label}</label>
      {failed && <p role="alert">{errorLabel}</p>}
      <div ref={host} aria-disabled={disabled} />
    </div>
  );
}
